#!/usr/bin/env python3
"""Generate independently discoverable Siri UI tests from the saved room fixture.

Each invocation has its own setup/teardown: XCTest's legacy Siri activation
timeout aborts the current test method, so a loop cannot exercise a matrix.
These tests require the explicit robot-start interception banner on the phone.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent / "SiriDeviceUITests"
MODES = [
    ("vacuum", "vacuum", "Vacuum"),
    ("mop", "mop", "Mop"),
    ("vacuumMop", "vacuum and mop", "Vacuum & mop"),
    ("vacuumThenMop", "vacuum then mop", "Vacuum, then mop"),
]


def generate() -> None:
    rooms = json.loads((ROOT / "RoomCases.json").read_text())
    if not isinstance(rooms, list) or not 1 <= len(rooms) <= 100:
        raise ValueError("Expected 1–100 saved room names")
    if any(not isinstance(room, str) or not room.strip() or len(room) > 100
           or any(ord(character) < 32 for character in room) for room in rooms):
        raise ValueError("Room names must be nonempty, bounded strings")
    if len(set(room.casefold() for room in rooms)) != len(rooms):
        raise ValueError("Ambiguous room names require separate disambiguation tests")
    literal = lambda value: json.dumps(value, ensure_ascii=False)
    lines = ["// Generated by Tests/generate_siri_room_tests.py; do not edit.",
             "import XCTest", "", "@MainActor", "extension SiriRoutingUITests {"]
    for number, room in enumerate(rooms):
        for identifier, phrase, title in MODES:
            command = literal(f"Run Narwal {phrase} {room}")
            reply = literal(f"{title} in {room}.")
            lines += [f"    func testSavedRoom{number:02d}_{identifier}() {{",
                      f"        invoke({command}, expecting: {reply})", "    }"]
    lines += ["}", ""]
    (ROOT / "GeneratedSiriRoomTests.swift").write_text("\n".join(lines))
    print(f"Generated {len(rooms) * len(MODES)} independent Siri cases; no robot commands run by generation.")


if __name__ == "__main__":
    generate()
